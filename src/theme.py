def render_metric_card(
    icon,
    value,
    label,
    accent=None
):
    """
    Render one KPI card.

    Example:

        with col:
            render_metric_card(
                "🏨",
                "275",
                "Admissions",
                accent="#38BDF8"
            )
    """

    accent = accent or COLORS["teal"]

    st.markdown(
        f"""
        <div
            class="mimic-metric-card"
            style="--mimic-accent: {accent};"
        >

            <div class="mimic-metric-icon">
                {icon}
            </div>

            <div class="mimic-metric-value">
                {value}
            </div>

            <div class="mimic-metric-label">
                {label}
            </div>

        </div>
        """,
        unsafe_allow_html=True
    )


# ============================================================
# METRIC ROW
# ============================================================

def metric_row(columns, cards):
    """
    Render a row of KPI metric cards.

    Parameters
    ----------
    columns:
        Streamlit columns returned by st.columns()

    cards:
        List of dictionaries containing:

            icon
            value
            label
            accent (optional)
    """

    for col, card in zip(columns, cards):

        with col:

            render_metric_card(
                icon=card["icon"],
                value=card["value"],
                label=card["label"],
                accent=card.get("accent")
            )
