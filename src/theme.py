def render_hero(
    eyebrow,
    title,
    subtitle,
    accent=None
):
    """
    Render the page hero:

        eyebrow
        title
        subtitle
        ECG divider
    """

    accent = accent or COLORS["teal"]

    st.markdown(
        f"""
        <div class="mimic-eyebrow">
            {eyebrow}
        </div>

        <div class="mimic-hero-title">
            {title}
        </div>

        <p class="mimic-hero-subtitle">
            {subtitle}
        </p>
        """,
        unsafe_allow_html=True
    )

    st.markdown(
        ecg_divider(accent=accent),
        unsafe_allow_html=True
    )


# ============================================================
# METRIC CARD
