# THEME INJECTION
# ============================================================

def inject_theme():
    """
    Inject the shared MIMIC Analytics visual theme.

    This function deliberately does NOT attempt to detect
    Streamlit's light/dark theme with JavaScript.

    Streamlit already exposes theme colors through CSS variables
    such as --text-color and --secondary-text-color. Using those
    variables keeps custom components synchronized with the
    native Streamlit theme.
    """

    st.markdown(
        _CUSTOM_CSS,
        unsafe_allow_html=True
    )


# ============================================================
# ECG WAVEFORM
# ============================================================

def ecg_divider(accent=None, cycles=10, height=34):
    """
    Render the ECG waveform used as the dashboard's signature
    visual divider.
    """

    accent = accent or COLORS["teal"]

    cycle_width = 160
    baseline = height / 2

    segment_template = (
        "L{x0},{b} "
        "L{x1},{b} "
        "L{x2},{small_dip} "
        "L{x3},{big_peak} "
        "L{x4},{deep_trough} "
        "L{x5},{b} "
        "L{x6},{small_bump} "
        "L{x7},{b} "
    )

    path_parts = [
        f"M0,{baseline}"
    ]

    peak_amplitude = baseline * 0.85
    trough_amplitude = (height - baseline) * 0.7
    small_dip_amplitude = (height - baseline) * 0.35
    small_bump_amplitude = baseline * 0.3

    for cycle in range(cycles):

        x0 = cycle * cycle_width

        path_parts.append(
            segment_template.format(
                x0=x0 + 0,
                x1=x0 + 34,
                x2=x0 + 40,
                x3=x0 + 48,
                x4=x0 + 56,
                x5=x0 + 62,
                x6=x0 + 70,
                x7=x0 + 160,
                b=baseline,
                small_dip=baseline + small_dip_amplitude,
                big_peak=baseline - peak_amplitude,
                deep_trough=baseline + trough_amplitude,
                small_bump=baseline - small_bump_amplitude,
            )
        )

    path_d = " ".join(path_parts)

    total_width = cycles * cycle_width

    svg = f"""
    <div
        style="
            width:100%;
            overflow:hidden;
            margin:0.4rem 0 1.4rem 0;
        "
    >
        <svg
            viewBox="0 0 {total_width} {height}"
            preserveAspectRatio="none"
            width="100%"
            height="{height}"
        >
            <path
                d="{path_d}"
                fill="none"
                stroke="{accent}"
                stroke-width="1.6"
                stroke-linejoin="round"
                stroke-linecap="round"
                opacity="0.85"
            />
        </svg>
    </div>
    """

    return svg


